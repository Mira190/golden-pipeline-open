# ------------------------------------------------------------------ the command line
def run_cli(here: Path, command: str, *args: str) -> tuple[int, str]:
    """`golden COMMAND ...` run in the directory `here` (a plain directory): the exit code,
    0, 1 or 2, and what it printed. 2 means "refused, and here is why", which every parser
    error must end in."""
    out = io.StringIO()
    with watchdog(), contextlib.chdir(here), contextlib.redirect_stdout(out):
        code = cli.main([command, *args])
    text = out.getvalue()
    assert code in {0, 1, 2}
    if code == 2:
        # Split on newlines only: a workflow command ends at one, and a message may hold U+2028.
        assert text.rstrip("\n").split("\n")[-1].startswith(f"::error::golden {command}: ")
    return code, text


def fresh(workdir: Path, name: str) -> Path:
    """An empty directory to run one command line in."""
    path = workdir / "cli" / name
    shutil.rmtree(path, ignore_errors=True)
    path.mkdir(parents=True)
    return path


