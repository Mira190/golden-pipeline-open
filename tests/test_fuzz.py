def nested(value: Any, *keys: str) -> Any:
    for key in keys:
        if not isinstance(value, dict):
            return None
        value = value.get(key)
    return value


def event_payloads() -> st.SearchStrategy[bytes]:
    """The structure-aware and the raw layer of a GitHub event file."""
    return st.one_of(
        raw(EVENT_TOKENS),
        damaged_json(PR_EVENT),
        damaged_json(MERGE_EVENT),
        bytes_of(JSON_JUNK.flatmap(json_texts)),
    )


@FUZZ
@given(name=st.sampled_from(EVENT_NAMES), blob=event_payloads())
def test_an_event_is_refused_or_names_the_commit_to_judge(workdir, name, blob):
    """`base()` is empty only when the event has no change to judge. A pull request or merge
    group event whose payload does not name its base must be refused: an empty base would skip
    every gate, so a damaged payload would read as a change with nothing in it."""
    path = put(workdir, "event.json", blob)
    with mock.patch.dict(os.environ, {"GITHUB_EVENT_PATH": str(path), "GITHUB_EVENT_NAME": name}):
        event = guarded(plan.Event.from_env, ValueError)
    if event is REFUSED:
        return
    assert event.name == name
    assert isinstance(event.payload, dict)
    base = guarded(event.base, ValueError)
    if base is REFUSED:
        return
    if name in BASE_EVENTS:
        sha = (
            nested(event.payload, "merge_group", "base_sha")
            if name == "merge_group"
            else nested(event.payload, "pull_request", "base", "sha")
        )
        assert type(sha) is str
        assert sha
        assert base == sha
    else:
        assert base == ""


def check_decision(decision: Any, payload: Any, name: str, api: Any) -> None:
    """The opt-out counts (report-only) only when a second person verifiably applied the label."""
    assert isinstance(decision, optout.Decision)
    assert type(decision.report_only) is bool
    assert type(decision.note) is str
    if not decision.report_only:
        return
    author = nested(payload, "pull_request", "user", "login")
    labels = nested(payload, "pull_request", "labels")
    assert type(author) is str
    assert author
    assert isinstance(labels, list)
    assert LABEL in [nested(lbl, "name") for lbl in labels]
    if name == "pull_request" and nested(payload, "label", "name") == LABEL:
        who = nested(payload, "sender", "login")
    else:
        who = None
        for event in api if isinstance(api, list) else []:
            if nested(event, "event") == "labeled" and nested(event, "label", "name") == LABEL:
                login = nested(event, "actor", "login")
                who = login if type(login) is str and login else None
    assert type(who) is str, "a login that is not a name counted as a second person"
    assert who
    assert who != author, "the author approved their own opt-out"
    assert decision.note == f"label `{LABEL}` applied by @{who} (PR by @{author})"


