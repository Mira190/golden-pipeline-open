@dataclass
class MutantsTree:
    meta: dict[str, Any]
    mutated: str
    source: str
    placed: list[tuple[int, str, str]]


@st.composite
def mutants_trees(draw: st.DrawFn) -> MutantsTree:
    """What mutmut leaves in `mutants/` for `pkg/mod.py`, and where its survivors are."""
    source: list[str] = []
    mutated: list[str] = []
    codes: dict[str, int | None] = {}
    placed = []
    for i in range(draw(st.integers(1, 3))):
        source += draw(st.lists(st.sampled_from(["", "# note", "import os"]), max_size=2))
        start = len(source) + 1
        body = [f"    v{j} = {j}" for j in range(draw(st.integers(1, 4)))]
        source += [f"def f{i}(a):", *body]
        mutated += [f"def x_f{i}__mutmut_orig(a):", *body]
        for n in range(1, draw(st.integers(1, 3)) + 1):
            at = draw(st.integers(0, len(body) - 1))
            changed = [*body[:at], f"    v{at} = {at} + 1", *body[at + 1 :]]
            mutated += [f"def x_f{i}__mutmut_{n}(a):", *changed]
            key = f"pkg.mod.x_f{i}__mutmut_{n}"
            codes[key] = draw(st.sampled_from([0, 0, 1, 3, 5, 33, 36, 34, 37, None]))
            if codes[key] in {0, 5, 33}:
                status = "survived" if codes[key] == 0 else "no-coverage"
                placed.append((start + 1 + at, status, key))
        mutated += [f"def f{i}(a):", "    return None"]
    meta = {
        "exit_code_by_key": codes,
        "durations_by_key": dict.fromkeys(codes, 0.25),
        "type_check_error_by_key": {},
        "tests_by_mangled_function_name": {"x_f0": ["tests/test_a.py::test_f"]},
        "hash_by_function_name": {"x_f0": "0" * 8},
    }
    return MutantsTree(meta, "\n".join(mutated), "\n".join(source), placed)


def write_tree(
    workdir: Path, stats: bytes, meta: bytes | None, mutated: bytes | None, source: bytes | None
) -> Path:
    root = workdir / "tree"
    shutil.rmtree(root, ignore_errors=True)
    report = put(root, "mutants/mutmut-cicd-stats.json", stats)
    for name, data in (
        ("mutants/pkg/mod.py.meta", meta),
        ("mutants/pkg/mod.py", mutated),
        ("pkg/mod.py", source),
    ):
        if data is not None:
            put(root, name, data)
    return report


def piece(valid: bytes, damaged_: st.SearchStrategy[bytes]) -> st.SearchStrategy[bytes | None]:
    return st.one_of(st.just(valid), damaged_, st.none())


def check_survivors(lived: list[mutation.Mutant], source: bytes | None, lines: Any) -> None:
    """Survivors sit on lines of the source file, in order, inside the changed lines. The file
    is read as Python reads text, where a lone carriage return ends a line too."""
    text = source.decode("utf-8", "replace") if source is not None else ""
    count = len(text.replace("\r\n", "\n").replace("\r", "\n").split("\n"))
    for m in lived:
        assert m.file == "pkg/mod.py"
        assert 1 <= m.line <= max(count, 1) or source is None
        if lines is not None:
            assert any(lo <= m.line <= hi for lo, hi in lines.get("pkg/mod.py", []))
    assert [(m.file, m.line) for m in lived] == sorted((m.file, m.line) for m in lived)


