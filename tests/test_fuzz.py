# What one example may take. Real inputs parse in microseconds; a parser that needs seconds on
# a few kilobytes is stuck (catastrophic backtracking, an exponential entity expansion).
WATCHDOG_SECONDS = 20.0


class HangError(AssertionError):
    """A parser did not come back within the watchdog."""


@contextlib.contextmanager
def watchdog(seconds: float = WATCHDOG_SECONDS) -> Iterator[None]:
    """Fail an example that does not finish. SIGALRM, so a loop in C code is interrupted too;
    a timer that is already armed (pytest-timeout's) is restored, less the time spent here."""
    if (
        not hasattr(signal, "setitimer")
        or threading.current_thread() is not threading.main_thread()
    ):
        yield
        return

    def alarm(signum: int, frame: object) -> None:
        raise HangError(f"still running after {seconds:g} s")

    previous = signal.signal(signal.SIGALRM, alarm)
    outer, interval = signal.getitimer(signal.ITIMER_REAL)
    started = time.monotonic()
    signal.setitimer(signal.ITIMER_REAL, seconds)
    try:
        yield
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        signal.signal(signal.SIGALRM, previous)
        if outer:
            left = max(outer - (time.monotonic() - started), 0.001)
            signal.setitimer(signal.ITIMER_REAL, left, interval)


REFUSED = object()


def guarded(call: Callable[[], Any], *errors: type[Exception]) -> Any:
    """What `call()` returns, or REFUSED when it raises exactly one of the documented errors.

    Exactly: a `UnicodeDecodeError`, `JSONDecodeError` or `TOMLDecodeError` is a `ValueError`
    too, but it names no file and no reason, so it must be wrapped, not passed on.
    """
    with watchdog():
        try:
            return call()
        except errors as exc:
            error = exc
    if type(error) not in errors:
        raise AssertionError(f"{type(error).__name__} escaped: {error}") from error
    assert str(error).strip(), "the error says nothing"
    return REFUSED


