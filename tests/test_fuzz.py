def nest_toml(depth: int, shape: str) -> str:
    opens = {"l": "[", "o": "{a = "}
    closes = {"l": "]", "o": "}"}
    shapes = [shape] * depth if shape != "m" else ["lo"[i % 2] for i in range(depth)]
    return "".join(opens[s] for s in shapes) + "0" + "".join(closes[s] for s in reversed(shapes))


def toml_float(value: float) -> str:
    if math.isnan(value):
        return "nan"
    return ("inf" if value > 0 else "-inf") if math.isinf(value) else repr(value)


def toml_value(value: Any) -> str:
    """A Python value as TOML. TOML has no null: it is written as an empty string."""
    scalars = {type(None): lambda v: '""', bool: lambda v: str(v).lower(), int: str}
    scalars |= {float: toml_float, str: json.dumps, dt.date: dt.date.isoformat}
    scalars |= {dt.datetime: dt.datetime.isoformat}
    if isinstance(value, list):
        return "[" + ", ".join(map(toml_value, value)) + "]"
    if isinstance(value, dict):
        pairs = (f"{json.dumps(k)} = {toml_value(v)}" for k, v in value.items())
        return "{" + ", ".join(pairs) + "}"
    return scalars[type(value)](value)


def toml_text(mapping: dict[str, Any]) -> str:
    text = "\n".join(f"{json.dumps(k)} = {toml_value(v)}" for k, v in mapping.items())
    return TOML_DEEP.sub(lambda m: nest_toml(int(m[1]), m[2]), text)


@st.composite
def policies(draw: st.DrawFn) -> tuple[dict[str, Any], dict[str, float]]:
    """(a valid golden.toml as a mapping, the value every key must end up with)."""
    data: dict[str, Any] = {}
    wanted = {}
    for key, bound in config.BOUNDS.items():
        section, name = key.split(".")
        wanted[key] = float(bound.default)
        if draw(st.booleans()):
            low, high = sorted([bound.floor, bound.strictest])
            value = (
                draw(st.integers(int(low), int(high)))
                if bound.integer
                else draw(st.floats(low, high, allow_nan=False))
            )
            data.setdefault(section, {})[name] = value
            wanted[key] = float(value)
    if draw(st.booleans()):
        data["presence"] = {
            "exempt": draw(
                st.lists(st.sampled_from(["src/gen/**", "docs/*.md", "migrations/"]), max_size=3)
            )
        }
    waivers = {}
    for gate in draw(st.lists(st.sampled_from(config.GATES), max_size=3, unique=True)):
        days = draw(st.integers(-10, config.MAX_WAIVER_DAYS))
        waivers[gate] = {
            "reason": draw(st.sampled_from(["flaky vendor", "migration"])),
            "expires": TODAY + dt.timedelta(days),
        }
    if waivers:
        data["waivers"] = waivers
    return data, wanted


def check_policy(policy: config.Policy) -> None:
    """What every policy that is returned respects: the floors, whatever the file said."""
    assert set(policy.values) == set(config.BOUNDS)
    for key, bound in config.BOUNDS.items():
        value = policy.values[key]
        assert type(value) is float
        assert math.isfinite(value), key
        low, high = sorted([bound.floor, bound.strictest])
        assert low <= value <= high, f"{key} = {value} is outside {low}..{high}"
        assert not bound.integer or value.is_integer()
    assert all(type(e) is str for e in policy.exempt)
    assert not [e for e in policy.exempt if config.BLANKET_EXEMPT.match(e.strip().lstrip("/"))]
    for gate, waiver in policy.waivers.items():
        assert gate in config.GATES
        assert waiver.reason.strip()
        assert type(waiver.expires) is dt.date
        assert (waiver.expires - TODAY).days <= config.MAX_WAIVER_DAYS
    assert policy.deferred == ()


