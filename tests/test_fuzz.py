"""Fuzzing of every parser that reads untrusted input, for the one rule they all share: fail closed.

For ANY input a parser must return a well-formed result or raise the module's documented error
(`ValueError`, `PolicyError`), with a message a person can read. It must never raise anything
else (`KeyError`, `TypeError`, `RecursionError`, `UnicodeDecodeError`, `ElementTree.ParseError`
...), never hang, and never turn garbage into a *passing* result. A gate that crashes with a
traceback still blocks the merge, but with no reason; a gate that reads garbage as "no findings"
lets the merge through. Fuzzing measures that rule over many thousands of inputs per parser
instead of a handful of hand-picked ones.

Two layers of inputs per parser, both generated by Hypothesis:

* structure-aware: a valid document with fields deleted, nulled, retyped (a number as a string,
  a list as an object, NaN, infinity, 10**400), nested a thousand levels deep, truncated,
  re-encoded (BOM, UTF-16, Latin-1, stray bytes, NUL) or empty;
* raw: arbitrary bytes, arbitrary text and token soup made of the format's own keywords.

The tests assert the contract and nothing else: the error is exactly the documented type, the
result is well-formed, and the verdict cannot be improved by damage (damaged mutation counts
never raise the score, damaged SARIF never loses a finding, a damaged event never grants the
test-presence opt-out). A watchdog turns a hang into a failure that names the input.

Run it:

    uv run pytest tests/test_fuzz.py                                     # fast profile, ~10 s
    HYPOTHESIS_PROFILE=fuzz uv run pytest tests/test_fuzz.py -n auto     # long run, no deadline
    HYPOTHESIS_PROFILE=fuzz FUZZ_EXAMPLES=500000 uv run pytest tests/test_fuzz.py -k sarif -n auto
    HYPOTHESIS_PROFILE=fuzz uv run pytest tests/test_fuzz.py -n 0 --hypothesis-show-statistics

The fast profile runs 40 examples per test and is `derandomize=True`: the 10x random-order
re-run of the flake gate and every CI run see the same examples, so a latent parser bug cannot
turn up as a flake on an unrelated pull request. The `fuzz` profile is random, runs 50,000
examples per test (about 40 minutes for this file on four cores; `FUZZ_EXAMPLES` changes the
number) and has no deadline. It keeps its failures in the example database (`.hypothesis/`),
so a crash it finds is replayed first on the next run, and prints a failing example with
`@reproduce_failure`. When a long run finds a crash, fix the parser, then add the minimal input
as a plain regression test next to the parser's own tests, under a `# found by
tests/test_fuzz.py` comment.
"""

