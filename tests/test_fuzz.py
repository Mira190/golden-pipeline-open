def expected_tally(statuses: list[str | None]) -> dict[str, int]:
    return {name: Counter(statuses)[name] for name in SCORES}


@st.composite
def stryker_reports(draw: st.DrawFn) -> Report:
    files: dict[str, Any] = {}
    seen, lived = [], []
    rooted = draw(st.booleans())  # Stryker.NET names files by absolute path, under projectRoot
    for name in draw(
        st.lists(st.sampled_from(["src/a.ts", "src/b.js", "lib/c.mts"]), max_size=3, unique=True)
    ):
        mutants = []
        for status in draw(st.lists(st.sampled_from(sorted(STRYKER_STATUSES)), max_size=6)):
            line = draw(st.integers(1, 40))
            location = {"start": {"line": line, "column": 1}, "end": {"line": line, "column": 9}}
            mutants.append(
                {"id": str(len(seen)), "mutatorName": "ArithmeticOperator", "replacement": "-",
                 "status": status, "location": location}
            )  # fmt: skip
            seen.append(STRYKER_STATUSES[status])
            if status in {"Survived", "NoCoverage"}:
                lived.append((name, line, "survived" if status == "Survived" else "no-coverage"))
        files[f"/work/{name}" if rooted else f"./{name}"] = {
            "language": "typescript",
            "source": "x",
            "mutants": mutants,
        }
    doc = {"schemaVersion": "2", "thresholds": {"high": 80, "low": 60}, "files": files}
    if rooted:
        doc["projectRoot"] = "/work"
    return Report(doc, expected_tally(seen), lived)


