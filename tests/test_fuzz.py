def test_the_watchdog_fails_an_example_that_does_not_finish():
    if (
        not hasattr(signal, "setitimer")
        or threading.current_thread() is not threading.main_thread()
    ):
        pytest.skip("the watchdog needs SIGALRM in the main thread")

    def spin():
        while True:
            pass

    with pytest.raises(HangError, match=r"still running after 0\.2 s"), watchdog(0.2):
        spin()


def test_the_watchdog_hands_back_a_timer_that_was_already_armed():
    if (
        not hasattr(signal, "setitimer")
        or threading.current_thread() is not threading.main_thread()
    ):
        pytest.skip("the watchdog needs SIGALRM in the main thread")
    previous = signal.signal(signal.SIGALRM, lambda signum, frame: None)
    signal.setitimer(signal.ITIMER_REAL, 100)
    try:
        with watchdog(5):
            pass
        left, _ = signal.getitimer(signal.ITIMER_REAL)
        assert 90 < left <= 100
        assert signal.getsignal(signal.SIGALRM) is not None
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        signal.signal(signal.SIGALRM, previous)


# ----------------------------------------------------------------- bytes and text
NASTY = [
    "\x00", "\r", "\n", "\t", '"', "'", "<", ">", "&", ";", ":", "\\", "{", "}", "[", "]", "=",
    ",", "#", "%", "\u0663", "\uff11", "\ufeff", "\u2028", "\x85", "\x0b", "\xe9", "\U0001f600",
    "\u01c1", "NaN", "Infinity", "-", "e", ".", " ",
]  # fmt: skip
SPECIAL = [
    b"", b" ", b"\n", b"\r\n", b"\x00", b"\xef\xbb\xbf", b"\xef\xbb\xbf\n", b"\xff\xfe",
    b"\xfe\xff", b"\xff", b"null", b"[]", b"{}", b"0", b'""', b"true", b"<", b"<a/>", b"{\n",
    b"[[[[", b"\xef\xbb\xbf{}", b"\xef\xbb\xbf<a/>",
]  # fmt: skip


@st.composite
def encoded(draw: st.DrawFn, text: str) -> bytes:
    """`text` as a file's bytes: mostly UTF-8, sometimes with a BOM, in another encoding,
    truncated, or with stray bytes."""
    how = draw(
        st.sampled_from(
            ["utf-8"] * 5 + ["bom", "utf-16", "latin-1", "truncate", "bad-utf8", "nul", "flip"]
        )
    )
    data = text.encode("utf-8")
    at = draw(st.integers(0, len(data)))
    junk = draw(st.sampled_from([b"\xff", b"\xc3\x28", b"\xe2\x82", b"\xed\xa0\x80"]))
    return {
        "utf-8": data,
        "bom": codecs.BOM_UTF8 + data,
        "utf-16": text.encode("utf-16"),
        "latin-1": text.encode("latin-1", "replace"),
        "truncate": data[:at],
        "bad-utf8": data[:at] + junk + data[at:],
        "nul": data[:at] + b"\x00" + data[at:],
        "flip": data[:at] + bytes([data[at] ^ 0xFF]) + data[at + 1 :] if at < len(data) else data,
    }[how]


@st.composite
def noisy(draw: st.DrawFn, text: str) -> str:
    """`text` with a few characters cut, repeated, inserted or replaced."""
    for _ in range(draw(st.integers(1, 4))):
        start = draw(st.integers(0, len(text)))
        end = min(len(text), start + draw(st.integers(0, 12)))
        op = draw(st.sampled_from(["cut", "dup", "insert", "replace"]))
        junk = draw(st.sampled_from(NASTY))
        text = {
            "cut": text[:start] + text[end:],
            "dup": text[:end] + text[start:],
            "insert": text[:start] + junk + text[start:],
            "replace": text[:start] + junk + text[end:],
        }[op]
    return text


def soup(tokens: list[str], max_size: int = 40) -> st.SearchStrategy[str]:
    """A format's own keywords in any order, with a little arbitrary text between them."""
    return st.lists(st.sampled_from(tokens) | st.text(max_size=3), max_size=max_size).map("".join)


def repeated(tokens: list[str]) -> st.SearchStrategy[bytes]:
    """One token, or a digit or a space, repeated up to 2,000 times: deep nests, long numbers and
    long runs, which is where a parser slows down or runs out of stack."""
    unit = st.sampled_from([*tokens, "9", " ", "0", "a", "\n"])
    return st.builds(
        lambda head, one, n, tail: (head + one * n + tail).encode(),
        st.sampled_from(tokens),
        unit,
        st.integers(1, 2000),
        st.sampled_from(tokens),
    )


def raw(tokens: list[str]) -> st.SearchStrategy[bytes]:
    """The raw layer: arbitrary bytes, arbitrary text, the format's token soup, and runs."""
    return st.one_of(
        st.sampled_from(SPECIAL),
        st.binary(max_size=300),
        st.text(max_size=200).flatmap(encoded),
        soup(tokens).flatmap(encoded),
        repeated(tokens),
    )


def bytes_of(texts: st.SearchStrategy[str]) -> st.SearchStrategy[bytes]:
    """Text as a file: as it is, or with character noise, or re-encoded."""
    return st.one_of(
        texts.map(lambda t: t.encode()),
        texts.flatmap(noisy).flatmap(encoded),
        texts.flatmap(encoded),
    )


# ------------------------------------------------------------------ damaging JSON
ODD: dict[str, list[Any]] = {
    "null": [None],
    "bool": [True, False],
    "int": [0, -1, 7, 2**63, -(2**63), 10**400],
    "float": [0.5, -0.0, 1e308, math.nan, math.inf, -math.inf],
    "str": ["", " ", "x", "0", "5", "-1", "nan", "inf", "1e999", "\x00", "\u0663"],
    "list": [[], [None], [[]], [0]],
    "dict": [{}, {"a": 1}],
}
DEEP = "@@deep:{n}:{shape}@@"


def kind_of(value: object) -> str:
    for kind, types in (
        ("null", type(None)),
        ("bool", bool),
        ("int", int),
        ("float", float),
        ("str", str),
        ("list", list),
        ("dict", dict),
    ):
        if isinstance(value, types):
            return kind
    return "other"


def slots(node: object, path: tuple[Any, ...] = ()) -> Iterator[tuple[Any, Any, tuple[Any, ...]]]:
    """Every place in a JSON document a value sits: (container, key, path)."""
    items = (
        list(node.items()) if isinstance(node, dict) else list(enumerate(node))
        if isinstance(node, list)
        else []
    )  # fmt: skip
    for key, value in items:
        yield node, key, (*path, key)
        yield from slots(value, (*path, key))


@st.composite
def damaged(
    draw: st.DrawFn,
    doc: object,
    where: Callable[[tuple[Any, ...]], bool] = lambda path: True,
    keep: Callable[[tuple[Any, ...]], bool] = lambda path: False,
    count: int = 3,
    deep_max: int = 10**6,
) -> object:
    """`doc` with up to `count` fields deleted, nulled, retyped, nested deeply or wrapped.

    Only the places `where` accepts are touched, and the ones `keep` names are never deleted
    (a deleted optional field is a valid document, not garbage). Only a field of another JSON
    type replaces a value, and no place is damaged twice (a second damage could put back a
    different but valid value), so no damage is a valid document with another meaning.
    """
    doc = copy.deepcopy(doc)
    touched: list[tuple[Any, ...]] = []
    for _ in range(draw(st.integers(1, count))):
        found = [
            (c, k, p)
            for c, k, p in slots(doc)
            if where(p) and not any(p[: len(t)] == t or t[: len(p)] == p for t in touched)
        ]
        if not found:
            break
        container, key, path = draw(st.sampled_from(found))
        touched.append(path)
        ops = ["null", "retype", "retype", "deep", "wrap"]
        if isinstance(container, dict) and not keep(path):
            ops += ["delete", "delete"]
        match draw(st.sampled_from(ops)):
            case "delete":
                del container[key]
            case "null":
                container[key] = None
            case "retype":
                kinds = [k for k in ODD if k != kind_of(container[key])]
                container[key] = copy.deepcopy(
                    draw(st.sampled_from(ODD[draw(st.sampled_from(kinds))]))
                )
            case "deep":
                big = [d for d in (900, 1100, 5000, 70_000) if d <= deep_max]
                depth = draw(st.one_of(st.integers(1, 30), st.sampled_from(big or [30])))
                shape = draw(st.sampled_from("lom"))
                container[key] = DEEP.format(n=depth, shape=shape)
            case "wrap":
                container[key] = draw(st.sampled_from([[container[key]], {"x": container[key]}]))
    return doc


def nest(depth: int, shape: str) -> str:
    """`[[[...]]]`, `{"a":{"a":...}}` or the two alternating, `depth` levels deep."""
    opens = {"l": "[", "o": '{"a":'}
    closes = {"l": "]", "o": "}"}
    shapes = [shape] * depth if shape != "m" else ["lo"[i % 2] for i in range(depth)]
    return "".join(opens[s] for s in shapes) + "0" + "".join(closes[s] for s in reversed(shapes))


DEEP_MARKER = re.compile(r'"@@deep:(\d+):([lom])@@"')


def deep_object(depth: int, shape: str) -> Any:
    value: Any = 0
    for level in range(depth):
        value = [value] if (shape if shape != "m" else "lo"[level % 2]) == "l" else {"a": value}
    return value


def materialize(node: Any) -> Any:
    """The placeholders of a damaged document as the nested Python objects they stand for."""
    if isinstance(node, str) and (found := DEEP_MARKER.fullmatch(f'"{node}"')):
        return deep_object(int(found[1]), found[2])
    if isinstance(node, dict):
        return {k: materialize(v) for k, v in node.items()}
    if isinstance(node, list):
        return [materialize(v) for v in node]
    return node


def damaged_objects(doc: object, **options: Any) -> st.SearchStrategy[Any]:
    """A damaged document as Python objects, nested as deep as a parser could have made them."""
    return damaged(doc, deep_max=500, **options).map(materialize)


def dumps(doc: object, ensure_ascii: bool = True) -> str:
    """JSON text, `NaN` and `Infinity` as Python writes them, deep placeholders expanded."""
    text = json.dumps(doc, ensure_ascii=ensure_ascii)
    return DEEP_MARKER.sub(lambda m: nest(int(m[1]), m[2]), text)


def json_texts(doc: object) -> st.SearchStrategy[str]:
    """A valid document as JSON text."""
    return st.booleans().map(lambda ascii_only: dumps(doc, ascii_only))


def damaged_json(doc: object, **options: Any) -> st.SearchStrategy[bytes]:
    """The structure-aware layer for JSON: a damaged document, as a file."""
    return bytes_of(damaged(doc, **options).flatmap(json_texts))


# ------------------------------------------------------------------- lines of text
@st.composite
def damaged_lines(draw: st.DrawFn, lines: list[str]) -> str:
    """Line-oriented text (LCOV, a Go coverprofile, JSON Lines) with lines dropped, repeated,
    swapped, blanked, glued together or replaced by junk."""
    lines = list(lines)
    for _ in range(draw(st.integers(1, 3))):
        if not lines:
            break
        at = draw(st.integers(0, len(lines) - 1))
        match draw(st.sampled_from(["drop", "dup", "swap", "blank", "glue", "junk", "pad"])):
            case "drop":
                del lines[at]
            case "dup":
                lines.insert(at, lines[at])
            case "swap":
                lines.reverse()
            case "blank":
                lines[at] = ""
            case "glue":
                lines[at : at + 2] = ["".join(lines[at : at + 2])]
            case "junk":
                lines[at] = draw(st.sampled_from(NASTY)) + draw(st.text(max_size=6))
            case "pad":
                lines[at] = f"  {lines[at]}\t "
    return draw(st.sampled_from(["\n", "\r\n", "\r"])).join(lines)


# --------------------------------------------------------------------- XML nodes
@dataclass
class Node:
    tag: str
    attrs: dict[str, str] = field(default_factory=dict)
    kids: list[Node] = field(default_factory=list)
    text: str = ""

    def render(self) -> str:
        attrs = "".join(f' {k}="{html.escape(v)}"' for k, v in self.attrs.items())
        if not self.kids and not self.text:
            return f"<{self.tag}{attrs}/>"
        body = html.escape(self.text) + "".join(k.render() for k in self.kids)
        return f"<{self.tag}{attrs}>{body}</{self.tag}>"

    def walk(self) -> Iterator[Node]:
        yield self
        for kid in self.kids:
            yield from kid.walk()


ODD_ATTRS = [
    "", " ", "x", "-1", "-0", "1e5", "1.5", "nan", "inf", "99999999999999999999999999", "0x1F",
    "\u0663", "\uff11", "+3", "1_000", " 5 ", "\x00",
]  # fmt: skip
XML_PROLOGS = [
    "",
    '<?xml version="1.0"?>',
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<?xml version="1.0" encoding="utf-16"?>',
    '<?xml version="1.0" encoding="latin-1"?>',
    '<?xml version="1.0" encoding="no-such-codec"?>',
    '<?xml version="2.0"?>',
    "<!-- comment -->",
    '<!DOCTYPE coverage SYSTEM "http://dtd.invalid/coverage.dtd">',
    '<!DOCTYPE c [<!ENTITY a "aaaaaaaaaa"><!ENTITY b "&a;&a;&a;&a;&a;&a;&a;&a;&a;&a;">'
    '<!ENTITY c "&b;&b;&b;&b;&b;&b;&b;&b;&b;&b;"><!ENTITY d "&c;&c;&c;&c;&c;&c;&c;&c;&c;&c;">]>',
    '<!DOCTYPE c [<!ENTITY x SYSTEM "file:///etc/passwd">]>',
]


@st.composite
def damaged_xml(draw: st.DrawFn, root: Node) -> str:
    """The tree with attributes deleted or garbled, tags renamed, children dropped, repeated or
    nested, and a prologue (DOCTYPE with entities, a wrong encoding declaration) in front."""
    root = copy.deepcopy(root)
    for _ in range(draw(st.integers(0, 3))):
        nodes = list(root.walk())
        node = draw(st.sampled_from(nodes))
        match draw(
            st.sampled_from(["del_attr", "bad_attr", "rename", "drop", "dup", "nest", "text"])
        ):
            case "del_attr" if node.attrs:
                del node.attrs[draw(st.sampled_from(sorted(node.attrs)))]
            case "bad_attr" if node.attrs:
                node.attrs[draw(st.sampled_from(sorted(node.attrs)))] = draw(
                    st.sampled_from(ODD_ATTRS)
                )
            case "rename":
                node.tag = draw(
                    st.sampled_from(["x", "line", "class", "coverage", "testcase", "a b", ""])
                )
            case "drop" if node.kids:
                del node.kids[draw(st.integers(0, len(node.kids) - 1))]
            case "dup" if node.kids:
                node.kids.append(copy.deepcopy(draw(st.sampled_from(node.kids))))
            case "nest":
                node.kids = [Node("x", {}, node.kids)]
            case "text":
                node.tag += draw(st.sampled_from(["&", "<", "\x00", "\u0663", ":"]))
    return draw(st.sampled_from(XML_PROLOGS)) + root.render()


