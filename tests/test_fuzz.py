    """(a SARIF log, the (level, file, region) of the findings a correct reader gets from it)."""
    runs, wanted = [], []
    for r in range(draw(st.integers(1, 2))):
        results = []
        for n in range(draw(st.integers(0, 4))):
            level = draw(st.sampled_from(sorted(FINDING_LEVELS)))
            uri = draw(st.sampled_from(["src/a.py", "lib/b.py", "c.py"]))
            region = draw(st.sampled_from([None, (3, 3), (2, 9)]))
            physical: dict[str, Any] = {"artifactLocation": {"uri": uri}}
            if region:
                physical["region"] = {"startLine": region[0], "endLine": region[1]}
            result: dict[str, Any] = {
                "ruleId": f"R{r}{n}", "level": level, "message": {"text": f"m{r}{n}"},
                "locations": [{"physicalLocation": physical}],
                "suppressions": [], "baselineState": "new", "kind": "fail",
            }  # fmt: skip
            results.append(result)
            wanted.append((level, uri, region))
        runs.append({"tool": {"driver": {"name": "t", "rules": []}}, "results": results})
    return {"version": "2.1.0", "runs": runs}, wanted


