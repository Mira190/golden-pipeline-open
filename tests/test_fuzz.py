@st.composite
def deploy_logs(draw: st.DrawFn) -> list[dict[str, Any]]:
    records = []
    for n in range(draw(st.integers(0, 5))):
        zone = dt.timezone(dt.timedelta(hours=draw(st.integers(-12, 14))))
        committed = (EPOCH + dt.timedelta(minutes=draw(st.integers(0, 10_000)))).astimezone(zone)
        deployed = committed + dt.timedelta(minutes=draw(st.integers(0, 5000)))
        failed = draw(st.booleans())
        restored = deployed + dt.timedelta(minutes=draw(st.integers(0, 900)))
        record: dict[str, Any] = {
            "sha": f"abc{n}",
            "committed_at": committed.isoformat(),
            "deployed_at": deployed.isoformat(),
            "failed": failed,
            "restored_at": restored.isoformat() if failed and draw(st.booleans()) else None,
        }
        if draw(st.booleans()):
            record["rework"] = draw(st.booleans())
        records.append(record)
    return records


def check_dora(records: list[dict[str, Any]]) -> None:
    """Records that parsed are what the log's schema says they are, and so are the metrics."""
    for record in records:
        assert type(record["failed"]) is bool
        times = {k: dt.datetime.fromisoformat(record[k]) for k in dora.TIMESTAMPS if record.get(k)}
        assert all(t.tzinfo is not None for t in times.values())
        assert times["deployed_at"] >= times["committed_at"]
        assert "restored_at" not in times or times["restored_at"] >= times["deployed_at"]
        assert "rework" not in record or type(record["rework"]) is bool
    metrics = guarded(lambda: dora.compute(records), ValueError)
    if not records:
        assert metrics is REFUSED
        return
    assert 0 <= metrics.change_failure_rate <= 1
    assert metrics.deploys_per_day > 0
    assert metrics.lead_time_hours_p50 >= 0
    assert metrics.time_to_restore_hours_p50 is None or metrics.time_to_restore_hours_p50 >= 0
    assert metrics.deployment_rework_rate is None or 0 <= metrics.deployment_rework_rate <= 1


def parse_log(text: str) -> Any:
    return guarded(lambda: dora.parse_log(text), ValueError)


