@dataclass
class Cobertura:
    root: Node
    names: list[str]
    sources: list[str]
    hits: list[int]


@st.composite
def cobertura(draw: st.DrawFn) -> Cobertura:
    files = draw(st.lists(st.tuples(NAMES, st.lists(st.integers(0, 4), max_size=5)), max_size=4))
    sources = draw(st.lists(st.sampled_from(["src", "/abs/src/", ".", ""]), max_size=2))
    hits = [h for _, per_file in files for h in per_file]
    attrs = {"version": "7"}
    if draw(st.booleans()):
        attrs |= {"lines-covered": str(sum(h > 0 for h in hits)), "lines-valid": str(len(hits))}
    classes = [
        Node(
            "class",
            {"filename": name},
            [
                Node(
                    "lines",
                    {},
                    [
                        Node("line", {"number": str(n), "hits": str(h)})
                        for n, h in enumerate(per_file, 1)
                    ],
                )
            ],
        )
        for name, per_file in files
    ]
    root = Node(
        "coverage",
        attrs,
        [
            Node("sources", {}, [Node("source", text=s) for s in sources]),
            Node("packages", {}, [Node("package", {}, [Node("classes", {}, classes)])]),
        ],
    )
    return Cobertura(root, [name for name, _ in files], sources, hits)


@st.composite
def lcov(draw: st.DrawFn) -> tuple[list[str], list[str], int, int]:
    """(lines, file names, lines found, lines hit) of an LCOV report."""
    records = []
    for name in draw(st.lists(NAMES, max_size=4)):
        found = draw(st.integers(0, 50))
        records.append((name, found, draw(st.integers(0, found))))
    lines = ["TN:"]
    for name, found, hit in records:
        lines += [f"SF:{name}", "DA:1,1", f"LF:{found}", f"LH:{hit}", "end_of_record"]
    names = [name.strip() for name, _, _ in records]
    return lines, names, sum(f for _, f, _ in records), sum(h for *_, h in records)


@st.composite
def gocover(draw: st.DrawFn) -> tuple[list[str], list[str], int, int]:
    """(lines, file names, statements, statements covered); a block may be repeated."""
    lines = [f"mode: {draw(st.sampled_from(['set', 'count', 'atomic']))}"]
    blocks: dict[str, tuple[int, int]] = {}
    names = []
    for _ in range(draw(st.integers(0, 8))):
        name = draw(st.sampled_from(["m/a.go", "m/b.go", "m/my dir/c.go"]))
        block = f"{name}:{draw(st.integers(1, 3))}.1,{draw(st.integers(4, 6))}.2"
        stmts, count = draw(st.integers(0, 9)), draw(st.integers(0, 3))
        if block in blocks:
            stmts = blocks[block][0]
        blocks[block] = (stmts, max(count, blocks.get(block, (0, 0))[1]))
        names.append(name)
        lines.append(f"{block} {stmts} {count}")
        if draw(st.booleans()):
            lines.append("")
    total = sum(s for s, _ in blocks.values())
    return lines, sorted(set(names)), total, sum(s for s, c in blocks.values() if c > 0)


